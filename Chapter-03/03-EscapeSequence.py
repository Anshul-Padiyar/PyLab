string = "Tiny changes\t-->\tremarkable results" # tab 
print(string)

string = "\"Tiny changes, remarkable results\"" # double quote 
print(string)

string = "'Tiny changes, remarkable results'" # single quote directly
print(string)

string = '\'Tiny changes, remarkable results\'' # single quote 
print(string)

string = "Tiny changes \\ remarkable results" # backslash 
print(string)